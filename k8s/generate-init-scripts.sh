#!/bin/sh
# Generates k8s/postgres-init-scripts.yaml from backend/migrations/*.sql.
# Re-run after adding or changing a migration. A test fails if the two drift apart.
set -e

cd "$(dirname "$0")/.."

{
  echo "# Generated by k8s/generate-init-scripts.sh from backend/migrations. Do not edit."
  kubectl create configmap postgres-init-scripts \
    --from-file=backend/migrations/ \
    --dry-run=client -o yaml
} > k8s/postgres-init-scripts.yaml

echo "Wrote k8s/postgres-init-scripts.yaml"
